from __future__ import annotations

import os
import platform
import shlex
import shutil
import subprocess
import tempfile
import tomllib
from pathlib import Path
from typing import Any

from .run import doctor


def _repository_root() -> Path:
    root = Path(__file__).resolve().parents[2]
    if not (root / "pyproject.toml").is_file():
        raise RuntimeError("setup-runtime must be run from a verifiable-pxrd checkout")
    return root


def _default_source_condition() -> Path:
    return _repository_root() / "experiments/agent-adaptation/conditions/pxrd-codex.toml"


def _portable_condition() -> Path:
    return (
        _repository_root()
        / "experiments/agent-adaptation/conditions/portable/gsas-codex.toml"
    )


def _read_installation(condition: Path) -> dict[str, dict[str, Any]]:
    with condition.open("rb") as stream:
        raw = tomllib.load(stream)
    installation = raw.get("environment", {}).get("installation", {})
    required = {"matsci", "gsasii"}
    missing = required - set(installation)
    if missing:
        raise ValueError(f"condition lacks setup payloads: {sorted(missing)}")
    return {name: dict(installation[name]) for name in sorted(required)}


def _probe(python: Path, expression: str) -> dict[str, Any]:
    if not python.is_file():
        return {"valid": False, "reason": f"missing {python}"}
    process = subprocess.run(
        [str(python), "-c", expression],
        text=True,
        capture_output=True,
        check=False,
    )
    return {
        "valid": process.returncode == 0,
        "returncode": process.returncode,
        "stdout": process.stdout.strip(),
        "stderr": process.stderr.strip(),
    }


def _validate_matsci(target: Path) -> dict[str, Any]:
    result = _probe(
        target / "bin/python",
        "import ase, numpy, pymatgen, pyxtal, scipy, spglib; print('ok')",
    )
    return {"component": "matsci", "path": str(target), **result}


def _validate_gsasii(target: Path, expected_commit: str) -> dict[str, Any]:
    result = _probe(
        target / "venv/bin/python",
        "from GSASII import GSASIIpath, GSASIIscriptable; "
        "print(GSASIIpath.GetVersionNumber())",
    )
    source = target / "source"
    if result["valid"] and not (source / ".git").is_dir():
        result["valid"] = False
        result["reason"] = f"missing pinned GSAS-II source checkout at {source}"
    elif result["valid"]:
        process = subprocess.run(
            ["git", "-C", str(source), "rev-parse", "HEAD"],
            text=True,
            capture_output=True,
            check=False,
        )
        actual = process.stdout.strip() if process.returncode == 0 else None
        result["source_commit"] = actual
        if actual != expected_commit:
            result["valid"] = False
            result["reason"] = f"GSAS-II commit {actual!r} does not match {expected_commit}"
    return {"component": "gsasii", "path": str(target), **result}


def _install(name: str, record: dict[str, Any], target: Path) -> None:
    if shutil.which("uv") is None:
        raise FileNotFoundError("uv is required; install it from https://docs.astral.sh/uv/")
    if name == "gsasii" and shutil.which("git") is None:
        raise FileNotFoundError("git is required to install GSAS-II")
    with tempfile.TemporaryDirectory(prefix=f"vpbench-{name}-") as temporary:
        root = Path(temporary)
        script = root / "install.sh"
        script.write_text(str(record["install_script"]), encoding="utf-8")
        script.chmod(0o700)
        lock = record.get("requirements_lock")
        if lock is not None:
            lock_name = "gsas-requirements.lock" if name == "gsasii" else "requirements.lock"
            (root / lock_name).write_text(str(lock), encoding="utf-8")
        subprocess.run(["/bin/bash", str(script), str(target)], check=True)


def _env_line(name: str, value: Path) -> str:
    return f"export {name}={shlex.quote(str(value.resolve()))}"


def _write_environment(
    path: Path,
    *,
    codex: Path,
    matsci: Path,
    gsasii: Path,
    cod_metadata: Path | None,
    cod_cifs: Path | None,
) -> str:
    lines = [
        "# Generated by `vpbench setup-runtime`; safe to source in bash or zsh.",
        _env_line("VPBENCH_CODEX", codex),
        _env_line("VPBENCH_MATSCI_ENV", matsci),
        _env_line("VPBENCH_GSAS_ENV", gsasii / "venv"),
    ]
    if cod_metadata is not None and cod_cifs is not None:
        lines.extend(
            [
                _env_line("VPBENCH_COD_METADATA", cod_metadata),
                _env_line("VPBENCH_COD_CIFS", cod_cifs),
            ]
        )
    text = "\n".join(lines) + "\n"
    if path.exists():
        if path.read_text(encoding="utf-8") != text:
            raise FileExistsError(f"refusing to replace a different environment file: {path}")
        return "reused"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return "created"


def setup_runtime(
    prefix: Path,
    *,
    source_condition: Path | None = None,
    codex: Path | None = None,
    cod_metadata: Path | None = None,
    cod_cifs: Path | None = None,
    environment_file: Path | None = None,
    dry_run: bool = False,
) -> dict[str, Any]:
    system = platform.system()
    if system not in {"Darwin", "Linux"}:
        raise RuntimeError(f"setup-runtime supports macOS and Linux, not {system}")
    if (cod_metadata is None) != (cod_cifs is None):
        raise ValueError("--cod-metadata and --cod-cifs must be supplied together")
    cod_metadata = cod_metadata.expanduser().resolve() if cod_metadata else None
    cod_cifs = cod_cifs.expanduser().resolve() if cod_cifs else None
    if cod_metadata is not None and not cod_metadata.is_file():
        raise FileNotFoundError(cod_metadata)
    if cod_cifs is not None and not cod_cifs.is_dir():
        raise FileNotFoundError(cod_cifs)

    detected_codex = codex or (Path(found) if (found := shutil.which("codex")) else None)
    if detected_codex is None or not detected_codex.expanduser().exists():
        raise FileNotFoundError("Codex CLI not found; install it or pass --codex")
    detected_codex = detected_codex.expanduser().resolve()
    source_condition = (source_condition or _default_source_condition()).expanduser().resolve()
    installation = _read_installation(source_condition)
    prefix = prefix.expanduser().resolve()
    matsci = prefix / "matsci"
    gsasii = prefix / "gsas2"
    environment_file = (environment_file or prefix / "runtime.env").expanduser().resolve()

    plan = {
        "platform": system,
        "prefix": str(prefix),
        "source_condition": str(source_condition),
        "portable_condition": str(_portable_condition()),
        "components": {
            "matsci": str(matsci),
            "gsasii": str(gsasii),
        },
        "environment_file": str(environment_file),
        "dicvol_included": False,
    }
    if dry_run:
        return {"valid": True, "dry_run": True, **plan}

    components: dict[str, dict[str, Any]] = {}
    matsci_before = _validate_matsci(matsci)
    if matsci.exists() and not matsci_before["valid"]:
        raise RuntimeError(f"existing materials-science environment is invalid: {matsci}")
    if not matsci.exists():
        _install("matsci", installation["matsci"], matsci)
    components["matsci"] = {
        **_validate_matsci(matsci),
        "action": "reused" if matsci_before["valid"] else "installed",
    }

    expected_commit = str(installation["gsasii"]["commit"])
    gsas_before = _validate_gsasii(gsasii, expected_commit)
    if gsasii.exists() and not gsas_before["valid"]:
        raise RuntimeError(f"existing GSAS-II environment is invalid: {gsasii}")
    if not gsasii.exists():
        _install("gsasii", installation["gsasii"], gsasii)
    components["gsasii"] = {
        **_validate_gsasii(gsasii, expected_commit),
        "action": "reused" if gsas_before["valid"] else "installed",
    }
    if not all(record["valid"] for record in components.values()):
        raise RuntimeError(f"runtime validation failed: {components}")

    env_action = _write_environment(
        environment_file,
        codex=detected_codex,
        matsci=matsci,
        gsasii=gsasii,
        cod_metadata=cod_metadata,
        cod_cifs=cod_cifs,
    )
    environment = {
        "VPBENCH_CODEX": str(detected_codex),
        "VPBENCH_MATSCI_ENV": str(matsci),
        "VPBENCH_GSAS_ENV": str(gsasii / "venv"),
    }
    if cod_metadata is not None and cod_cifs is not None:
        environment["VPBENCH_COD_METADATA"] = str(cod_metadata)
        environment["VPBENCH_COD_CIFS"] = str(cod_cifs)
    os.environ.update(environment)
    condition_health = doctor(_portable_condition())
    return {
        "valid": True,
        "dry_run": False,
        **plan,
        "components": components,
        "environment_file_action": env_action,
        "condition_health": condition_health,
        "next_command": f"source {shlex.quote(str(environment_file))}",
    }
